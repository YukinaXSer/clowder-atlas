import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const notices = [];
const host = { Plugin: class {}, ItemView: class {}, PluginSettingTab: class {}, Modal: class {}, Notice: class { constructor(s) { notices.push(s); } }, requestUrl: async () => ({}) };
const box = { module: { exports: {} }, require: () => host, console, URL, Set, Map, setTimeout, clearTimeout, setInterval() {}, clearInterval() {} };
vm.runInNewContext(fs.readFileSync(new URL('../src/main.js', import.meta.url), 'utf8') + '\nmodule.exports.helpers={passageMessage,passageShown,threadTitle};', box);
const Plugin = box.module.exports, h = Plugin.helpers;
const p = (path, text, line=0) => ({ path, basename: path.split('/').pop().replace(/\.md$/, ''), text, from: { line, ch: 0 }, to: { line, ch: text.length } });
const a = p('a/同名.md', 'A原文'), b = p('b/同名.md', 'B原文', 3);
const plugin = new Plugin();
plugin.settings = { revisionTargets: {} };
plugin.saveData = async data => { plugin.saved = JSON.parse(JSON.stringify(data)); };
plugin.openCafeChat = async () => {};
plugin.app = { workspace: { getLeavesOfType: () => [] } };
const attach = value => plugin.askAboutPassage({ getCursor: side => value[side === 'from' ? 'from' : 'to'], getRange: () => value.text }, { file: value });

await attach(a);
await attach(b);
assert.equal(plugin.chatPassages?.length, 2, 'second note must append instead of replacing the first');
await attach(b);
assert.equal(plugin.chatPassages.length, 2, 'the same selection is deduplicated');
assert.equal(plugin.saved.chatPassages.length, 2, 'unsent tray persists');
const message = h.passageMessage(plugin.chatPassages, '对照二者');
assert.ok(message.includes('[#1') && message.includes('[#2') && message.includes('A原文') && message.includes('B原文'));
assert.ok(message.includes('a/同名.md') && message.includes('b/同名.md'), 'same names keep distinct source paths');
assert.ok(!message.includes('放进一个'), 'multi-source synthesis must not promise automatic replacement');
assert.match(h.threadTitle('新对话', { passage: plugin.chatPassages }), /2 篇（2 段）/);
const snapshot = [...plugin.chatPassages];
await attach(p('large.md', 'x'.repeat(90000)));
assert.equal(plugin.chatPassages.length, 2, 'overflow preserves the original tray');

await plugin.rememberPassageRequest('multi', 'http://a', 't', snapshot);
assert.equal(plugin.settings.revisionTargets.multi, undefined, 'multi-source requests must not become legacy single-passage replacement targets');
await plugin.bindRevisionMessage('multi', 'u-multi');
await plugin.rememberPassageRequest('single', 'http://a', 't', [a]);
await plugin.bindRevisionMessage('single', 'u-single');
const reply = ids => ({ threadId: 't', lifecycle: { kind: 'response', inputMessageIds: ids } });
assert.equal(plugin.revisionTargetForReply('http://a', reply(['u-multi'])).target, null, 'multi-source revision stays copy-only even after a later single request');
assert.equal(plugin.revisionTargetForReply('http://a', reply(['u-single'])).target.path, a.path);
assert.equal(plugin.revisionTargetForReply('http://a', reply(['u-single', 'u-multi'])).target, null);
assert.equal(plugin.passagesForReply('http://a', reply(['u-multi']), 't').length, 2);
assert.equal(plugin.passagesForReply('http://b', reply(['u-multi']), 't').length, 0);
assert.equal(plugin.passagesForReply('http://a', reply(['u-multi']), 'other').length, 0);
plugin.chatPassage = null;
assert.equal(plugin.chatPassages.length, 0);
assert.equal(plugin.passagesForReply('http://a', reply(['u-multi']), 't').length, 2, 'request sources survive tray changes');
await plugin.setChatPassages([a]);
const inFlight = plugin.chatPassages;
await plugin.setChatPassages([]);
await attach(a);
await plugin.consumeChatPassages(inFlight);
assert.equal(plugin.chatPassages.length, 1, 'removing and reattaching the same text during a send creates a new selection intent');
console.log('PASS multi-passage collection, payload, persistence and request-bound provenance');
